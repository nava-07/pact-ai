import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import { configured, env } from './config/env.js';
import { errorHandler } from './middleware/auth.js';
import { auth } from './routes/auth.js'; import { pacts } from './routes/pacts.js'; import { paypal } from './routes/paypal.js'; import { ledger } from './routes/ledger.js'; import { ai } from './routes/ai.js'; import { notifications } from './routes/notifications.js';
export const app = express();
app.set('trust proxy', 1); app.use(helmet()); app.use(cors({ origin: env.CLIENT_URL, credentials: true })); app.use(express.json({ limit: '200kb' })); app.use(cookieParser());
app.use('/api', rateLimit({ windowMs: 60_000, limit: 120 })); app.use('/api/auth', rateLimit({ windowMs: 15 * 60_000, limit: 30 }));
app.get('/api/health', (_req, res) => { res.json({ ok: true, config: configured, paypalMode: env.PAYPAL_BASE_URL.includes('sandbox') ? 'sandbox' : 'live' }); });
app.use('/api', auth, pacts, paypal, ledger, ai, notifications); app.use((_req, res) => { res.status(404).json({ error: 'Not found' }); }); app.use(errorHandler);
